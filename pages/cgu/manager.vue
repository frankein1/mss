        finalités pour lesquelles les données à caractère personnel sont
        traitées. Par ailleurs, les données à caractère personnel ne peuvent
        être utilisées ultérieurement que pour des finalités compatibles aux
        finalités initiales.
      </p>
      <h3>Obligations générales de l’ANCT</h3>
      <p>En qualité de Sous-traitant, l’ANCT s’engage à&nbsp;:</p>
      <ul>
        <li>
          traiter les données à caractère personnel uniquement pour fournir les
          services relatifs à la plateforme et pour les seules finalités, les
          seuls destinataires et les seules durées de conservation des données
          définies dans les présentes CGU&nbsp;;
        </li>
        <li>
          traiter les données personnelles conformément aux instructions des
          ministères sociaux, des communes, des CCAS, des CIAS et des structures
          d’accompagnement social. Si l’ANCT considère qu’une instruction
          constitue une violation du RGPD, il en informe immédiatement la
          structure concernée. En outre, si l’ANCT est tenue de procéder à un
          transfert de données à caractère personnel vers un pays tiers ou à une
          organisation internationale, en vertu du droit de l’Union ou du droit
          de l’Etat membre auquel il est soumis, il doit informer les ministères
          sociaux, les communes, les CCAS, les CIAS et les structures
          d’accompagnement social de cette obligation juridique avant le
          traitement, sauf si le droit concerné interdit une telle information
          pour des motifs importants d'intérêt public&nbsp;;
        </li>
        <li>
          garantir la confidentialité des données à caractère personnel&nbsp;;
        </li>
        <li>
          veiller à ce que les personnes autorisées à traiter les données à
          caractère personnel au sein de l’ANCT s’engagent à respecter la
          confidentialité des données à caractère personnel&nbsp;; ait reçues la
          formation nécessaire en matière de protection des données à caractère
          personnel&nbsp;;
        </li>
        <li>
          fournir l’ensemble des informations nécessaires à la réalisation de la
          documentation produite dans le cadre de la mise en conformité du
          traitement avec le RGPD (mentions d’information, analyse d’impact,
          mentions légales et conditions générales d’utilisation)&nbsp;;
        </li>
        <li>
          s’engage à respecter les obligations de transparence et de traçabilité
          et de mettre en œuvre les principes de privacy by design (prise en
          compte de la vie privée tout au long du processus).
        </li>
      </ul>
      <p>
        L’ANCT ne sera en aucun cas responsable du non-respect par les
        ministères sociaux, communes, CCAS, CIAS et structures d’accompagnement
