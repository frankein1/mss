        </li>
        <li>
          autoriser l’ANCT à traiter les données à caractère personnel pour leur
          propre compte&nbsp;;
        </li>
        <li>
          documenter par écrit toute instruction concernant le traitement des
          données à caractère personnel données à l’ANCT&nbsp;;
        </li>
        <li>
          veiller, au préalable et pendant toute la durée du traitement des
          données à caractère personnel, au respect des obligations prévues par
          le RGPD&nbsp;;
        </li>
        <li>
          superviser le traitement des données à caractère personnel, y compris
          réaliser les audits et les inspections auprès de l’ANCT&nbsp;;
        </li>
        <li>
          mettre en œuvre le cadre juridique en vigueur, notamment les
