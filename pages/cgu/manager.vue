        verrouillage des portes) et informatiques (anonymisation, stockage des
        données en base de données, cloisonnement des données, mesures de
        traçabilité, surveillance, protection des réseaux, sauvegarde,
        antivirus, politique de mot de passe sécurisé) et notamment des mesures
        organisationnelles (politique de contrôle d’accès des données,
        sensibilisation des utilisateurs à la protection des données à caractère
        personnel, procédures en cas de fuite des données personnelles et audits
        réguliers des procédures et traitements).
      </p>
      <p>
        La mise en œuvre des mesures de sécurité et techniques relève de la
        responsabilité de l’ANCT, sous réserve de l’absence de négligence grave
