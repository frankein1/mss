          documentation produite dans le cadre de la mise en conformité du
          traitement avec le RGPD et tenir le registre des traitements&nbsp;;
        </li>
        <li>
          veiller à ce que les personnes autorisées à traiter les données à
          caractère personnel soient soumises à une obligation légale de
          confidentialité&nbsp;et reçoivent la sensibilisation nécessaire en
          matière de protection des données à caractère personnel&nbsp;;
        </li>
        <li>
          veiller à l’information des personnes concernées par le traitement des
          données à caractère personnel.
        </li>
      </ul>
      <p>
        Les ministères sociaux, les communes, les CCAS, les CIAS ou les
        structures d’accompagnement social sont responsables du respect du RGPD
        en ce qui concerne le présent traitement de données à caractère
        personnel.
      </p>
      <p>
        Le Responsable de traitement demeure chargé d’intégrer dans ses propres
        outils de conformité le traitement «&nbsp;MonSuiviSocial&nbsp;».
      </p>
