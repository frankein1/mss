      <h2>
        Pour quelles raisons sommes-nous susceptibles de traiter des
        données&nbsp;?
      </h2>
      <p>
        La plateforme mon Suivi Social a pour objectif de faciliter le suivi
        social des bénéficiaires des ministères sociaux, des communes, des CCAS,
        des CIAS ou structures d’accompagnement social.
      </p>
      <p>Des données à caractère personnel seront traitées pour&nbsp;:</p>
      <ul>
        <li>
          Fournir les prestations définies dans le cadre d’un contrat conclu
          entre l’organisme et le bénéficiaire ou son représentant légal&nbsp;;
        </li>
        <li>
          Assurer la gestion du dossier administratif du bénéficiaire&nbsp;;
        </li>
        <li>
          Instruire, gérer et, le cas échéant, ouvrir les droits et/ou verser
          les prestations sociales légales et facultatives&nbsp;;
        </li>
        <li>Permettre la prise de rendez-vous des bénéficiaires&nbsp;;</li>
        <li>
          Offrir un accompagnement social et médico-social adapté aux
          difficultés rencontrées ayant notamment pour objet d’élaborer un
          projet personnalisé d’accompagnement&nbsp;;
        </li>
        <li>
          Assurer la gestion administrative financière et comptable de
          l’établissement, du service ou de l’organisme&nbsp;;
        </li>
        <li>
          Établir des statistiques, des études internes et des enquêtes de
          satisfaction.
        </li>
      </ul>
      <h2>
        Sommes-nous autorisés à traiter des données à caractère personnel&nbsp;?
      </h2>
      <p>
        Le traitement de données est réalisé sur le fondement de l’article 6 du
        RGPD.
      </p>
      <p>
        Lorsque Mon Suivi Social est utilisé par les ministères sociaux ou les
        communes, le traitement est fondé sur l’exécution d’une mission
        d’intérêt public ou relevant de l’exercice de l’autorité publique dont
        sont investis les ministères sociaux ou communes en tant que
        responsables de traitement au sens de l’article 6-e du RGPD.
      </p>
      <p>
        Lorsque Mon Suivi Social est utilisé par un CCAS ou un CIAS, le
        traitement est fondé sur l’exécution d’une mission d’intérêt public ou
        relevant de l’exercice de l’autorité publique dont sont investis les
        CCAS et CIAS en tant que responsables de traitement au sens de l’article
        6-e du RPGD, à savoir&nbsp;: l’article L 123-5 du code de l’action
        sociale et des familles.
      </p>
      <p>
        Lorsque Mon Suivi Social est utilisé par une structure d’accompagnement
        social de droit privé, le traitement est fondé soit&nbsp;sur les
        intérêts légitimes poursuivis par la structure d’accompagnement social
        en tant que responsable de traitement au sens de l’article 6-f du
        RGPD&nbsp;; soit sur le consentement des personnes concernées par le
        traitement au sens de l’article 6-a du RGPD.
      </p>
      <p>
        Il appartient à chaque structure d’accompagnement social, responsable de
        traitement, de déterminer ce fondement. Chaque responsable de traitement
        doit être en mesure de démontrer sur quelle base légale repose le
        présent traitement.
      </p>
      <p>
        Il en est de même pour le traitement des données de santé qui est soumis
        aux conditions de l’article 9 du RGPD. Il est rappelé que le responsable
        de traitement ne peut traiter les données de santé que s’il remplit
        l’une des conditions de l’article 9 du RGPD et qu’il doit être en mesure
        de démontrer le respect de ces conditions.
      </p>
      <p>
        Spécifiquement, le NIR est traité uniquement par les collectivités
        territoriales, CCAS et les CIAS sur le fondement de l’article L. 263-4-1
        du code de l’action sociale et des familles et du
        <a
          href="https://www.legifrance.gouv.fr/jorf/id/JORFTEXT000038396526/"
          target="_blank"
          rel="noopener external"
          >Décret n°219-341 du 19 avril 2019</a
        >
        relatif à la mise en œuvre de traitements comportant l’usage du numéro
        d’inscription au répertoire national d’identification des personnes
        physiques ou nécessitant la consultation de ce répertoire.
      </p>
