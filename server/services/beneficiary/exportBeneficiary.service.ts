import { ExportBeneficiaryInput } from '~/server/schema/beneficiary/exportbeneficiary.schema'
import { SecurityRuleContext } from '~/server/security'
import { BeneficiaryRepo, UserRepo } from '~/server/database'
import {
  PDFDocument as PDFDocumentLib,
  PageSizes,
  StandardFonts,
  rgb
} from 'pdf-lib'
import puppeteer from 'puppeteer'
import PDFDocument from 'pdfkit'

export const exportBeneficiary = async ({
  ctx,
  input
}: {
  ctx: SecurityRuleContext
  input: ExportBeneficiaryInput
}) => {
  const beneficiaryDetails = await BeneficiaryRepo.findUniqueOrThrow(ctx.user, {
    where: { id: input.beneficiaryId }
  })
  const user = await UserRepo.findUniqueOrThrow(ctx.user, {
    where: { id: ctx.user.id }
  })

  const stream = await new Promise<Buffer>(resolve => {
    const pdfDoc = new PDFDocument()
    const buffs: unknown[] = []
    pdfDoc.on('data', d => {
      buffs.push(d as readonly Uint8Array[])
    })
    pdfDoc.on('end', () => {
      resolve(Buffer.concat(buffs as readonly Uint8Array[]))
    })
    pdfDoc.fontSize(25).text('Some text with an embedded font!', 100, 100)
    pdfDoc.end()
  })

  const dataStringKit = stream.toString('base64')

  // Info about size
  // Size are in typography point (pt) 1pt = 1/72 inch
  // 1pt +/- = 0,188 mm

  const pdfDoc = await PDFDocumentLib.create()
  const helvetica = await pdfDoc.embedFont(StandardFonts.Helvetica)
  const helveticaBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold)

  // la fiche pdf récapitulative de l'archivage (qui a archivé, quelle date, le motif de l'archivage,
  // la date d'ouverture du dossier, nombre de suivis). Nom du fichier : Résumé_archive

  const introductionText = `– Dossier crée le ${beneficiaryDetails.created?.toLocaleDateString()}
– Dossier archivé le ${new Date().toLocaleDateString()}
– Archive réalisée par ${user.firstName} ${user.lastName}`

  const motiveText = `
Motif de l’archive : 
– ${input.reason}${input.date ? ' (le ' + input.date + ')' : ''}
${input.clarification ? '– ' + input.clarification : ''}`

  const page = pdfDoc.addPage(PageSizes.A4)
  const { width, height } = page.getSize()
  const titleFontSize = 28
  const fontSize = 16

  page.moveTo(20, 20)
  page.drawText(
    beneficiaryDetails.firstName + ' ' + beneficiaryDetails.usualName,
    {
      x: 20,
      y: height - 20 - fontSize,
      size: titleFontSize,
      font: helveticaBold,
      color: rgb(0, 0.53, 0.71)
    }
  )
  page.moveDown(20)
  page.drawText(introductionText + motiveText, {
    size: fontSize,
    font: helvetica,
    maxWidth: width - 40
  })
  page.moveDown(20)
  page.drawText(motiveText, {
    size: fontSize,
    font: helvetica,
    maxWidth: width - 40
  })
  await pdfDoc.save()

  const data = await pdfDoc.saveAsBase64({ dataUri: true })

  // TEST puppetter
  const content = `<style type="text/css" media="all">
    @import url(https://fonts.googleapis.com/css?family=Lato:300,400,700); 
    * {
      font-family: 'Lato', sans-serif;
      font-size: 16px;
    }
</style>
<html>

    <body>
    <p>
        This is generated by Puppeteer using the Handlebar template and this message is passed as a variable to the
        template.</p>
        <hr />
        <p>Another paragraph</p>
    </body>

</html>`
  const browser = await puppeteer.launch()
  const puppeteerPage = await browser.newPage()
  await puppeteerPage.setContent(content)
  await puppeteerPage.emulateMediaType('screen')
  await puppeteerPage.goto('data:text/html,' + content, {
    waitUntil: 'networkidle0'
  })
  const byteArray = await puppeteerPage.pdf({
    format: 'A4',
    landscape: false,
    scale: 1,
    printBackground: true,
    margin: {
      top: 20,
      bottom: 20,
      left: 20,
      right: 20
    }
  })

  const puppeteerPdf = uint8ArrayToBase64(byteArray)

  return { data, beneficiaryDetails, puppeteerPdf }
}

function uint8ArrayToBase64(
  uint8Array: Uint8Array,
  mimeType = 'application/pdf'
) {
  // Convertir le Uint8Array en chaîne binaire
  const binaryString = Array.from(uint8Array)
    .map(byte => String.fromCharCode(byte))
    .join('')

  // Encoder la chaîne binaire en base64
  const base64String = btoa(binaryString)

  // Créer l'URL data: avec le type MIME et la chaîne base64
  return `data:${mimeType};base64,${base64String}`
}
